def initialize_parameters(layer_dims=(4, 8, 6, 3)):
    np.random.seed(42)
    params = {}
    params['W1'] = np.random.randn(layer_dims[0], layer_dims[1]) * np.sqrt(2.0 / layer_dims[0])
    params['b1'] = np.zeros((1, layer_dims[1]))
    params['W2'] = np.random.randn(layer_dims[1], layer_dims[2]) * np.sqrt(2.0 / layer_dims[1])
    params['b2'] = np.zeros((1, layer_dims[2]))
    params['W3'] = np.random.randn(layer_dims[2], layer_dims[3]) * np.sqrt(2.0 / layer_dims[2])
    params['b3'] = np.zeros((1, layer_dims[3]))
    return params

def sigmoid(Z):
    return 1 / (1 + np.exp(-np.clip(Z, -500, 500)))

def sigmoid_derivative(A):
    return A * (1 - A)

def softmax(Z):
    exp_Z = np.exp(Z - np.max(Z, axis=1, keepdims=True))
    return exp_Z / np.sum(exp_Z, axis=1, keepdims=True)

def forward_propagation(X, params):
    cache = {}
    cache['A0'] = X
    cache['Z1'] = np.dot(cache['A0'], params['W1']) + params['b1']
    cache['A1'] = sigmoid(cache['Z1'])
    cache['Z2'] = np.dot(cache['A1'], params['W2']) + params['b2']
    cache['A2'] = sigmoid(cache['Z2'])
    cache['Z3'] = np.dot(cache['A2'], params['W3']) + params['b3']
    cache['A3'] = softmax(cache['Z3'])
    return cache['A3'], cache

def compute_loss(Y_hat, Y):
    m = Y.shape[0]
    Y_hat = np.clip(Y_hat, 1e-15, 1 - 1e-15)
    loss = -np.sum(Y * np.log(Y_hat)) / m
    return loss

def backward_propagation(cache, Y, params):
    m = Y.shape[0]
    gradients = {}

    dZ3 = cache["A3"] - Y
    gradients["dW3"] = np.dot(cache["A2"].T, dZ3) / m
    gradients["db3"] = np.sum(dZ3, axis=0, keepdims=True) / m

    dZ2 = np.dot(dZ3, params["W3"].T) * sigmoid_derivative(cache["A2"])
    gradients["dW2"] = np.dot(cache["A1"].T, dZ2) / m
    gradients["db2"] = np.sum(dZ2, axis=0, keepdims=True) / m

    dZ1 = np.dot(dZ2, params["W2"].T) * sigmoid_derivative(cache["A1"])
    gradients["dW1"] = np.dot(cache["A0"].T, dZ1) / m
    gradients["db1"] = np.sum(dZ1, axis=0, keepdims=True) / m

    return gradients

def update_parameters(params, gradients, learning_rate):
    for key in params:
        if key.startswith('W'):
            params[key] -= learning_rate * gradients["dW" + key[1:]]
        elif key.startswith('b'):
            params[key] -= learning_rate * gradients["db" + key[1:]]
    return params

def fit(X_train, y_train, X_val, y_val, layer_dims=(4, 8, 6, 3), epochs=1000, lr=0.01, batch_size=16, patience=50):
    params = initialize_parameters(layer_dims)
    num_samples = X_train.shape[0]
    train_loss_history = []
    val_acc_history = []
    best_val_acc = 0.0
    patience_counter = 0
    best_weights = {k: v.copy() for k, v in params.items()}

    for epoch in range(epochs):
        permutation = np.random.permutation(num_samples)
        X_train_shuffled = X_train[permutation]
        y_train_shuffled = y_train[permutation]

        for i in range(0, num_samples, batch_size):
            X_batch = X_train_shuffled[i : i + batch_size]
            y_batch = y_train_shuffled[i : i + batch_size]

            _, cache = forward_propagation(X_batch, params)
            gradients = backward_propagation(cache, y_batch, params)
            params = update_parameters(params, gradients, lr)

        train_preds, _ = forward_propagation(X_train, params)
        train_loss = compute_loss(train_preds, y_train)
        train_loss_history.append(train_loss)

        val_preds, _ = forward_propagation(X_val, params)
        val_acc = np.mean(np.argmax(val_preds, axis=1) == np.argmax(y_val, axis=1))
        val_acc_history.append(val_acc)

        if val_acc > best_val_acc:
            best_val_acc = val_acc
            best_weights = {k: v.copy() for k, v in params.items()}
            patience_counter = 0
